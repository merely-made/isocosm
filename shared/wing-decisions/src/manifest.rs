//! The manifest (`design_docs/decisions.toml`) and the register, both
//! generated from what the index holds, never edited by hand.

use crate::docs::Entry;
use crate::model::Key;
use crate::scan::Facts;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// Every decision with its declared links and everything pointing back.
#[derive(Default)]
pub struct Manifest {
    pub items: BTreeMap<Key, Item>,
    pub errors: Vec<String>,
}

#[derive(Default)]
pub struct Item {
    pub entry: Option<Entry>,
    pub mentioned_by: BTreeSet<Key>,
    pub drawn_on_by: BTreeSet<Key>,
    pub amended_by: BTreeSet<Key>,
    pub replaced_by: BTreeSet<Key>,
    pub contradicted_by: BTreeSet<Key>,
    pub cited_in_docs: BTreeSet<String>,
    pub cited_in_code: BTreeSet<String>,
}

impl Manifest {
    pub fn build(files: &[(String, Facts)]) -> Manifest {
        let mut m = Manifest::default();
        for (_, f) in files {
            for e in &f.entries {
                m.errors.extend(e.errors.iter().cloned());
                let item = m.items.entry(e.key.clone()).or_default();
                if let Some(prev) = &item.entry {
                    m.errors.push(format!("{} declared twice: {}:{} and {}:{}", e.key, prev.source, prev.line, e.source, e.line));
                }
                item.entry = Some(e.clone());
            }
        }
        for (path, f) in files {
            for e in &f.entries {
                let l = &e.links;
                let back: [(&BTreeSet<Key>, fn(&mut Item) -> &mut BTreeSet<Key>); 5] = [
                    (&e.mentions, |i| &mut i.mentioned_by),
                    (&l.draws_on, |i| &mut i.drawn_on_by),
                    (&l.amends, |i| &mut i.amended_by),
                    (&l.replaces, |i| &mut i.replaced_by),
                    (&l.contradicts, |i| &mut i.contradicted_by),
                ];
                for (targets, field) in back {
                    for t in targets {
                        field(m.items.entry(t.clone()).or_default()).insert(e.key.clone());
                    }
                }
            }
            let code = crate::scan::is_rust(path);
            for (k, line) in &f.cites {
                let item = m.items.entry(k.clone()).or_default();
                if code {
                    item.cited_in_code.insert(format!("{path}:{line}"));
                } else {
                    item.cited_in_docs.insert(path.clone());
                }
            }
        }
        m
    }

    /// Deterministic TOML: cases by number, then plan decisions by key.
    /// `declared` keeps only what decisions declare, without line numbers: the
    /// committed manifest, which changes only when a decision does. Otherwise
    /// everything, citations and back-links included: the local derived view.
    pub fn to_toml(&self, declared: bool) -> String {
        let mut s = String::from(if declared {
            "# Generated by shared/wing-decisions: every decision and what it declares.\n# Never edited by hand; citations and back-links are derived locally\n# (`wing-decisions lookup`). DOC_POLICY, \"Decisions and doctrine\".\nschema = 1\n"
        } else {
            "# Derived by shared/wing-decisions: a local cache, never committed.\nschema = 1\n"
        });
        for (k, item) in &self.items {
            if declared && item.entry.is_none() {
                continue;
            }
            let table = match k {
                Key::Case(n) => format!("cases.\"{n}\""),
                Key::Plan(p, n) => format!("decisions.\"{p} D{n}\""),
            };
            let _ = write!(s, "\n[{table}]\n");
            match &item.entry {
                Some(e) => {
                    field(&mut s, "title", &e.title);
                    let src = if declared { e.source.clone() } else { format!("{}:{}", e.source, e.line) };
                    field(&mut s, "source", &src);
                    let l = &e.links;
                    if let Some(a) = &l.area {
                        field(&mut s, "area", a);
                    }
                    if let Some(x) = &l.summary {
                        field(&mut s, "summary", x);
                    }
                    keys(&mut s, "draws_on", &l.draws_on);
                    keys(&mut s, "amends", &l.amends);
                    keys(&mut s, "replaces", &l.replaces);
                    keys(&mut s, "contradicts", &l.contradicts);
                    list(&mut s, "plans", l.plans.iter());
                    list(&mut s, "governs", l.governs.iter());
                    if l.stack {
                        s.push_str("stack = true\n");
                    }
                    if !declared {
                        keys(&mut s, "mentions", &e.mentions);
                    }
                }
                None => s.push_str("live = false\n"),
            }
            if declared {
                continue;
            }
            keys(&mut s, "mentioned_by", &item.mentioned_by);
            keys(&mut s, "drawn_on_by", &item.drawn_on_by);
            keys(&mut s, "amended_by", &item.amended_by);
            keys(&mut s, "replaced_by", &item.replaced_by);
            keys(&mut s, "contradicted_by", &item.contradicted_by);
            list(&mut s, "cited_in_docs", item.cited_in_docs.iter());
            list(&mut s, "cited_in_code", item.cited_in_code.iter());
        }
        s
    }

    /// The register, once every live case carries an area and a summary;
    /// None until then (the migration is L3).
    pub fn register(&self, areas: &[String], dir: &str) -> Option<String> {
        let live: Vec<&Entry> =
            self.items.iter().filter(|(k, _)| matches!(k, Key::Case(_))).filter_map(|(_, i)| i.entry.as_ref()).collect();
        if live.is_empty() || live.iter().any(|e| e.links.area.is_none() || e.links.summary.is_none()) {
            return None;
        }
        let mut s = String::from(
            "# Case register\n\nGenerated by `shared/wing-decisions` from the design record's fields lines;\nnever edited by hand. Every live case, one line each, by area, with up to\nthree design docs that cite it. The record holds the words.\n",
        );
        for area in areas {
            let rows: Vec<&&Entry> = live.iter().filter(|e| e.links.area.as_deref() == Some(area)).collect();
            if rows.is_empty() {
                continue;
            }
            let _ = write!(s, "\n## {area}\n\n| Case | Decides | Cited by |\n| --- | --- | --- |\n");
            for e in rows {
                let cited = &self.items[&e.key].cited_in_docs;
                let by: Vec<String> = cited.iter().take(3).map(|p| doc_link(p, dir)).collect();
                let by = if by.is_empty() { "none".to_string() } else { by.join(", ") };
                let _ = writeln!(s, "| {} | {} | {} |", e.key, e.links.summary.as_deref().unwrap_or(""), by);
            }
        }
        Some(s)
    }
}

/// A citing doc as a link relative to the register's directory, labelled by
/// its keyword: `2026-09-22_sim_plan.md` reads "sim".
fn doc_link(path: &str, dir: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    let stem = name.trim_end_matches(".md");
    let stem = stem.get(11..).filter(|_| stem.as_bytes().get(10) == Some(&b'_')).unwrap_or(stem);
    let label = stem.trim_end_matches("_plan").trim_end_matches("_brief").replace('_', " ");
    format!("[{label}]({})", relative(path, dir))
}

fn relative(path: &str, dir: &str) -> String {
    let (p, d): (Vec<&str>, Vec<&str>) = (path.split('/').collect(), dir.split('/').filter(|s| !s.is_empty()).collect());
    let common = p.iter().zip(&d).take_while(|(a, b)| a == b).count();
    let mut out: Vec<&str> = vec![".."; d.len() - common];
    out.extend(&p[common..]);
    out.join("/")
}

fn esc(v: &str) -> String {
    let mut o = String::with_capacity(v.len() + 2);
    o.push('"');
    for c in v.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\t' => o.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(o, "\\u{:04X}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn field(s: &mut String, name: &str, v: &str) {
    let _ = writeln!(s, "{name} = {}", esc(v));
}

fn list<'a>(s: &mut String, name: &str, items: impl Iterator<Item = &'a String>) {
    let v: Vec<String> = items.map(|x| esc(x)).collect();
    if !v.is_empty() {
        let _ = writeln!(s, "{name} = [{}]", v.join(", "));
    }
}

fn keys(s: &mut String, name: &str, ks: &BTreeSet<Key>) {
    let v: Vec<String> = ks.iter().map(|k| k.to_string()).collect();
    list(s, name, v.iter());
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cite::Citer;
    use crate::scan::facts;

    #[test]
    fn back_links_and_citations_meet_in_one_item() {
        let plans = BTreeSet::from(["x".to_string()]);
        let c = Citer { max_case: 984, plans: &plans };
        let record = "## 0.\n\n1. **One.**\n\n2. **Two.** Per ruling 1.\n\n   Links: draws on 1 · summary Two\n\n## 1.\n";
        let files = vec![
            ("d/2026-09-18_wing_design_plan.md".to_string(), facts("d/2026-09-18_wing_design_plan.md", record, &c)),
            ("s/a.rs".to_string(), facts("s/a.rs", "// ruling 1\n", &c)),
        ];
        let m = Manifest::build(&files);
        let one = &m.items[&Key::Case(1)];
        assert!(one.drawn_on_by.contains(&Key::Case(2)));
        assert!(one.mentioned_by.contains(&Key::Case(2)));
        assert!(one.cited_in_code.contains("s/a.rs:1"));
        let t = m.to_toml(false);
        assert!(t.contains("[cases.\"2\"]\ntitle = \"Two\""));
        assert_eq!(t, Manifest::build(&files).to_toml(false));
        let d = m.to_toml(true);
        assert!(d.contains("draws_on = [\"1\"]") && !d.contains("cited_in_code") && !d.contains(".md:"));
        let parsed: toml::Table = t.parse().unwrap();
        assert!(parsed["cases"]["1"]["drawn_on_by"].as_array().is_some());
        assert!(m.register(&["A".to_string()], "d").is_none());
        assert_eq!(relative("design_docs/a.md", "design_docs"), "a.md");
        assert_eq!(relative("mesocosm/design_docs/b.md", "design_docs"), "../mesocosm/design_docs/b.md");
    }
}
