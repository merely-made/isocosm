use std::convert::Infallible;
use std::num::NonZeroU64;

use super::*;
use crate::{SlabCamera, SubjectKey, mesh::BodyDependencyRevision};
use BodyDetail::{Live, Sprite, Unavailable};
use RefreshClass::{Fast, Medium, Slow};

const BANDS: [[f32; 2]; 3] = [[12.0, 16.0], [26.0, 30.0], [44.0, 56.0]];
const VIEWPORT: [u32; 2] = [400, 400];
const FORWARD: [f32; 3] = [0.0, 0.0, 1.0];

fn policy(bands: [[f32; 2]; 3]) -> HybridPolicy {
    HybridPolicy::new(bands, [12, 4, 2].map(|n| NonZeroU64::new(n).unwrap())).unwrap()
}

fn slab(half_height: f32) -> SlabCamera {
    SlabCamera::new([0.0; 3], FORWARD, half_height, 1.0, 200.0).unwrap()
}

fn perspective() -> SlabCamera {
    SlabCamera::perspective(
        [0.0; 3],
        FORWARD,
        std::f32::consts::FRAC_PI_2,
        1.0,
        1.0,
        200.0,
    )
    .unwrap()
}

fn bounds(depth: f32) -> ([f32; 3], [f32; 3]) {
    ([-0.5, -1.0, depth], [0.5, 1.0, depth])
}

#[test]
fn camera_size_selects_per_body_and_examination_respects_held_detail() {
    let policy = policy(BANDS);
    let camera = slab(5.0);
    let near = projected_size(camera, bounds(4.0), VIEWPORT).unwrap();
    let far = projected_size(camera, bounds(40.0), VIEWPORT).unwrap();
    assert_eq!(near, far, "slab depth cannot change projected size");
    assert_eq!(policy.select(far, None, false, Live).choice.detail, Live);
    let zoomed_out = projected_size(slab(50.0), bounds(4.0), VIEWPORT).unwrap();
    assert_eq!(
        policy.select(zoomed_out, None, false, Live).choice.refresh,
        Slow
    );

    let camera = perspective();
    let near = projected_size(camera, bounds(4.0), VIEWPORT).unwrap();
    let far = projected_size(camera, bounds(40.0), VIEWPORT).unwrap();
    assert_eq!(
        policy.select(near, None, false, Live).choice,
        BodyChoice {
            detail: Live,
            refresh: Fast
        }
    );
    assert_eq!(
        policy.select(far, None, false, Live).choice,
        BodyChoice {
            detail: Sprite,
            refresh: Slow
        }
    );
    assert_eq!(policy.select(far, None, true, Live).choice.detail, Live);
    let pending = policy.select(near, None, true, Sprite);
    assert_eq!(pending.choice.detail, Sprite);
    assert!(pending.request_live_detail);
    assert!(!policy.select(near, None, false, Sprite).request_live_detail);
    let supplied = policy.select(near, Some(pending.choice), true, Live);
    assert_eq!(supplied.choice.detail, Live);
    assert!(!supplied.request_live_detail);
    assert_eq!(
        policy
            .select(near, Some(supplied.choice), true, Unavailable)
            .choice
            .detail,
        Unavailable
    );
}

#[test]
fn perspective_bounds_clip_edges_at_near_and_far_planes() {
    let camera = perspective();
    let crossing = projected_size(camera, ([-0.5, -1.0, -2.0], [0.5, 1.0, 4.0]), VIEWPORT);
    assert_eq!(crossing, projected_size(camera, bounds(1.0), VIEWPORT));
    assert!((crossing.unwrap() - 400.0).abs() < 0.01);
    assert_eq!(projected_size(camera, bounds(0.0), VIEWPORT), None);
    assert_eq!(projected_size(camera, bounds(201.0), VIEWPORT), None);
    assert_eq!(projected_size(camera, bounds(4.0), [0, 400]), None);
    assert_eq!(
        projected_size(camera, ([0.0; 3], [-1.0; 3]), VIEWPORT),
        None
    );
}

fn assert_in_band_stability(policy: HybridPolicy) {
    // Exercise both histories at each boundary, using projected sizes from
    // both cameras. A crossing is generated by zooming the slab or moving
    // the subject in perspective, with the same size sequence in both.
    let camera_sizes: [fn(f32) -> f32; 2] = [
        |px| projected_size(slab(400.0 / px), bounds(4.0), VIEWPORT).unwrap(),
        |px| projected_size(perspective(), bounds(400.0 / px), VIEWPORT).unwrap(),
    ];
    for camera_size in camera_sizes {
        for [leave, enter] in BANDS {
            let middle = (leave + enter) * 0.5;
            let delta = (enter - leave) * 0.25;
            for start in [leave - 1.0, enter + 1.0] {
                let initial = policy.select(camera_size(start), None, false, Live).choice;
                let mut previous = initial;
                for n in 0..64 {
                    let px = middle + if n % 2 == 0 { delta } else { -delta };
                    previous = policy
                        .select(camera_size(px), Some(previous), false, Live)
                        .choice;
                    assert_eq!(previous, initial, "in-band oscillation changed the choice");
                }
            }
        }
    }
}

#[test]
fn rung_and_refresh_classes_hold_in_their_bands() {
    assert_in_band_stability(policy(BANDS));
}

#[test]
#[should_panic(expected = "in-band oscillation changed the choice")]
fn zero_rung_band_control_fails() {
    assert_in_band_stability(policy([BANDS[0], BANDS[1], [50.0; 2]]));
}

#[test]
#[should_panic(expected = "in-band oscillation changed the choice")]
fn zero_refresh_band_control_fails() {
    assert_in_band_stability(policy([BANDS[0], [28.0; 2], BANDS[2]]));
}

fn assert_held_bound(select: impl Fn(f32, bool, BodyDetail) -> BodySelection) {
    for held in [Unavailable, Sprite, Live] {
        for pixels in [8.0, 28.0, 50.0, 80.0] {
            for examined in [false, true] {
                assert!(
                    select(pixels, examined, held).choice.detail <= held,
                    "exceeded held detail"
                );
            }
        }
    }
}

#[test]
fn selection_never_exceeds_held_detail() {
    assert_held_bound(|pixels, examined, held| policy(BANDS).select(pixels, None, examined, held));
}

#[test]
#[should_panic(expected = "exceeded held detail")]
fn removed_holding_bound_control_fails() {
    assert_held_bound(|pixels, examined, _| policy(BANDS).select(pixels, None, examined, Live));
}

fn source(frame: u64) -> SpriteSource {
    SpriteSource {
        pose_frame: frame,
        revisions: SpriteRevisions {
            anatomy: BodyDependencyRevision(1),
            appearance: 2,
            facing: 3,
            lighting: 4,
        },
    }
}

fn placement(subject: u64) -> SpritePlacement {
    SpritePlacement {
        subject: SubjectKey(subject),
        origin: [0.0; 3],
        scale: 1.0,
    }
}

#[test]
fn held_sprite_uses_current_origin_scale_and_pick_identity() {
    use crate::mesh::bake::{BakeParams, bake_facing, demo};

    let mut cache = SpriteCache::default();
    let body = placement(17);
    let period = policy(BANDS).refresh_period(Medium);
    let (hero, palette) = demo::hero();
    let entry = cache
        .resolve(body, source(4), 4, period, || {
            Ok::<_, Infallible>(bake_facing(&hero, &palette, 0, &BakeParams::default()))
        })
        .unwrap()
        .unwrap();
    assert!(entry.image.opaque_pixels() > 500);
    let pixels = entry.image.rgba.clone();
    let moved = SpritePlacement {
        origin: [9.0, 1.0, -12.0],
        scale: 0.8,
        ..body
    };
    let held = cache
        .resolve::<Infallible>(moved, source(5), 5, period, || panic!("unexpected bake"))
        .unwrap()
        .unwrap();
    assert_eq!(held.image.rgba, pixels);
    assert_eq!(held.placement, moved);
    assert_eq!(held.placement.subject, SubjectKey(17));
}

#[test]
fn revisions_rebake_only_the_affected_subject() {
    let mut cache = SpriteCache::default();
    let mut current = source(0);
    let period = policy(BANDS).refresh_period(Slow);
    for id in [1, 2] {
        cache
            .resolve(placement(id), current, 0, period, || Ok::<_, Infallible>(0))
            .unwrap();
    }
    let changes: [fn(&mut SpriteRevisions); 5] = [
        |r| r.anatomy.0 += 1,  // Growth.
        |r| r.anatomy.0 += 1,  // Injury.
        |r| r.appearance += 1, // Equipment appearance.
        |r| r.facing += 1,
        |r| r.lighting += 1,
    ];
    for (index, change) in changes.into_iter().enumerate() {
        let frame = index as u64 + 1;
        current.pose_frame = frame;
        change(&mut current.revisions);
        let changed = cache
            .resolve(placement(1), current, frame, period, || {
                Ok::<_, Infallible>(frame)
            })
            .unwrap()
            .unwrap();
        assert_eq!(*changed.image, frame);
        let other = cache
            .resolve::<Infallible>(placement(2), source(frame), frame, period, || {
                panic!("other subject rebaked")
            })
            .unwrap()
            .unwrap();
        assert_eq!(*other.image, 0);
    }
}

#[test]
fn reentry_checks_pose_age_against_the_current_class_and_retries_a_failed_bake() {
    let mut cache = SpriteCache::default();
    let body = placement(1);
    let slow = policy(BANDS).refresh_period(Slow);
    let fast = policy(BANDS).refresh_period(Fast);
    assert!(
        cache
            .resolve::<Infallible>(body, source(0), 2, fast, || panic!("stale cold pose"))
            .unwrap()
            .is_none()
    );
    assert!(
        cache
            .resolve::<Infallible>(body, source(3), 2, fast, || panic!("future cold pose"))
            .unwrap()
            .is_none()
    );
    cache
        .resolve(body, source(2), 2, slow, || Ok::<_, Infallible>(2))
        .unwrap();

    // On return after a live interval, the shorter period expires the image.
    let aged = cache
        .resolve(body, source(4), 4, fast, || Ok::<_, Infallible>(4))
        .unwrap()
        .unwrap();
    assert_eq!(*aged.image, 4);
    let mut changed = source(5);
    changed.revisions.lighting += 1;
    assert!(matches!(
        cache.resolve(body, changed, 5, slow, || Err("bake failed")),
        Err("bake failed")
    ));

    // A reversal to the original revisions still needs a bake after failure.
    let retry = cache
        .resolve(body, source(5), 5, slow, || Ok::<_, Infallible>(5))
        .unwrap()
        .unwrap();
    assert_eq!(*retry.image, 5);
}
